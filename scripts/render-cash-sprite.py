"""Renders the GTA cash HUD's Pricedown glyphs into one sprite, plus the metrics CashBar reads.

Pricedown's licence allows pre-rendered images but not web fonts, so the font itself is never committed or served.
Get it from Typodermic (or dafont) and run, with Pillow installed:

    python3 scripts/render-cash-sprite.py "path/to/Pricedown Bl.otf"

Writes public/experiences/gta/cash.png and src/experiences/gta/cashGlyphs.js.
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# GTA V's HUD green, with the game's heavy black outline. SIZE is about 3x the shown height, for sharp edges.
FILL, OUTLINE = (114, 204, 114, 255), (0, 0, 0, 255)
SIZE, STROKE, PAD = 96, 6, 2
PIECES = ['cash', '$', '+', *'0123456789']

root = Path(__file__).resolve().parent.parent
font = ImageFont.truetype(sys.argv[1], SIZE)
ascent, descent = font.getmetrics()
height = ascent + descent + 2 * (STROKE + PAD)

cells, x = {}, 0
for piece in PIECES:
    # Each cell is the piece's advance plus room for the outline; neighbours then overlap their outlines a little,
    # like the game's tight HUD text.
    width = round(font.getlength(piece)) + 2 * (STROKE + PAD)
    cells[piece] = [x, width]
    x += width

sprite = Image.new('RGBA', (x, height), (0, 0, 0, 0))
draw = ImageDraw.Draw(sprite)
for piece, (left, _) in cells.items():
    draw.text((left + STROKE + PAD, STROKE + PAD), piece, font=font, fill=FILL, stroke_width=STROKE, stroke_fill=OUTLINE)
sprite.save(root / 'public/experiences/gta/cash.png', optimize=True)

(root / 'src/experiences/gta/cashGlyphs.js').write_text(
    '// Generated by scripts/render-cash-sprite.py: where each piece sits in public/experiences/gta/cash.png, as\n'
    '// [x, width] in px, and the sprite\'s size. overlap is how far neighbouring pieces tuck into each other\'s outline.\n'
    f'export const CASH_SPRITE={json.dumps({"width": x, "height": height, "overlap": STROKE + PAD, "cells": cells}, separators=(",", ":"))};\n'
)
print(f'{x}x{height}')
